import {readFile,writeFile} from 'node:fs/promises'
import {createHash} from 'node:crypto'
import {brandPalette} from '../src/client/brand-palette.js'

const source=new URL('../assets/brand/',import.meta.url)
const read=(name:string)=>readFile(new URL(name,source),'utf8')
function artwork(svg:string){
  return svg.replace(/^.*?<svg\b[^>]*>/s,'').replace(/<\/svg>\s*$/,'')
    .replace(/<(title|desc)\b[^>]*>[\s\S]*?<\/\1>/g,'').replace(/\s+id="[^"]*"/g,'').trim()
}
const marks:Record<string,{viewBox:string;mono:string;color:string}>={}
for(const variant of ['d2','d1','c0','original']){
  const suffix=variant==='original'?'':`-${variant}`
  const monoSvg=await read(`fatfish-mark${suffix}-mono.svg`),colorSvg=await read(`fatfish-mark${suffix}.svg`)
  const viewBox=monoSvg.match(/<svg\b[^>]*\bviewBox="([^"]+)"/)?.[1]
  if(!viewBox||!colorSvg.includes(`viewBox="${viewBox}"`))throw new Error(`Mismatched brand viewBox: ${variant}`)
  marks[variant]={viewBox,mono:artwork(monoSvg).replaceAll(brandPalette.light.text,'currentColor'),color:colorRoles(artwork(colorSvg))}
}
function colorRoles(svg:string){
  for(const role of ['body','arc','text'] as const)svg=svg.replaceAll(brandPalette.light[role],`var(--fatfish-brand-${role}, ${brandPalette.light[role]})`)
  return svg
}
const brandSquare=await read('fatfish-brand-square-light.svg')
const signature=colorRoles(artwork(brandSquare).replace(/<rect\b[^>]*width="1024"[^>]*height="1024"[^>]*\/>/,''))
const chineseWordmark=brandSquare.match(/<g id="wordmark-chinese"[^>]*>[\s\S]*?<\/g>/)?.[0]
if(!chineseWordmark)throw new Error('Cannot find the approved Chinese wordmark.')
const wordmark={viewBox:'130 635 765 152',artwork:colorRoles(artwork(chineseWordmark))}
await writeFile(new URL('../src/client/brand-artwork.ts',import.meta.url),`// Approved vector outlines. Regenerate with: npx tsx scripts/generate-brand.ts\n// Local constants only; no runtime SVG parsing, fonts, images or network requests.\nexport const brandMarks=${JSON.stringify(marks,null,2)} as const\nexport const brandSignature=${JSON.stringify(signature)}\nexport const brandWordmark=${JSON.stringify(wordmark)} as const\n`)
for(const theme of ['light','dark']){
  const svg=await read(`fatfish-brand-square-${theme}.svg`)
  await writeFile(new URL(`fatfish-brand-transparent-${theme}.svg`,source),svg.replace(/<rect\b[^>]*width="1024"[^>]*height="1024"[^>]*\/>/,''))
}
// Browser/native icon slots share one resource, irrespective of raster frame resolution.
await writeFile(new URL('favicon.svg',source),await read('fatfish-icon-d1-dark.svg'))
const iconVersion=createHash('sha256').update((await read('favicon.svg')).replaceAll('\r\n','\n')).digest('hex').slice(0,16)
await writeFile(new URL('../src/host/brand-icon-version.ts',import.meta.url),`// Generated by scripts/generate-brand.ts from the fixed native icon SVG.\nexport const brandIconVersion=${JSON.stringify(iconVersion)}\n`)
await writeFile(new URL('../icon.svg',import.meta.url),await read('fatfish-icon-dark.svg'))
